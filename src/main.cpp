// ============================================================
// ESP-NOW SEND
// ============================================================

void sendEspNowValues()
{
    if (!espnow_ready || !espnow_enabled)
        return;

    uint32_t now = millis();

    if (now - lastEspNowSendMs < ESPNOW_INTERVAL_MS)
        return;

    DashPacket pkt{};

    pkt.rpm = ecu.data_valid ? ecu.rpm : 0;

    pkt.batt = fresh(
        trijekt.batteryValid,
        trijekt.lastBatteryMs
    ) ? ecu.batt : 0.0f;

    pkt.motor = fresh(
        trijekt.tempValid,
        trijekt.lastTempMs
    ) ? ecu.motor : 0.0f;

    pkt.dk = fresh(
        trijekt.throttleValid,
        trijekt.lastThrottleMs
    ) ? ecu.throttle_dk : 0.0f;

    pkt.gp = fresh(
        trijekt.throttleValid,
        trijekt.lastThrottleMs
    ) ? ecu.throttle_pedal : 0.0f;

    pkt.funk = 0;

    esp_err_t err = esp_now_send(
        espnow_broadcast_addr,
        reinterpret_cast<const uint8_t*>(&pkt),
        sizeof(pkt)
    );

    if (err != ESP_OK) {

        static uint32_t lastErrorMs = 0;

        if (now - lastErrorMs >= 5000) {

            Serial.printf(
                "ESP-NOW SEND ERROR: %d\n",
                (int)err
            );

            lastErrorMs = now;
        }
    }

    lastEspNowSendMs = now;
}

