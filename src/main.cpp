// ============================================================
// FIND EXISTING MODE 2 BUTTON
// ============================================================
//
// Searches for an LVGL label containing "MODE 2".
// Attaches an additional click callback to its parent.
//
// If your generated UI uses a different label or
// its existing callback changes screens afterward,
// connect open_trijekt_mode2() directly in screens.c.
//
// ============================================================

static bool findAndAttachMode2(lv_obj_t *parent)
{
    if (!parent)
        return false;

    uint32_t count = lv_obj_get_child_cnt(parent);

    for (uint32_t i = 0; i < count; i++) {

        lv_obj_t *child =
            lv_obj_get_child(parent, i);

        if (!child)
            continue;

        if (lv_obj_check_type(child, &lv_label_class)) {

            const char *label =
                lv_label_get_text(child);

            if (label) {

                String text = String(label);
                text.toLowerCase();

                if (
                    text.indexOf("mode 2") >= 0 ||
                    text.indexOf("mode2") >= 0
                ) {
                    lv_obj_t *button =
                        lv_obj_get_parent(child);

                    if (button) {

                        lv_obj_add_flag(
                            button,
                            LV_OBJ_FLAG_CLICKABLE
                        );

                        lv_obj_add_event_cb(
                            button,
                            mode2_button_event,
                            LV_EVENT_CLICKED,
                            nullptr
                        );

                        Serial.println(
                            "MODE 2 BUTTON CONNECTED"
                        );

                        return true;
                    }
                }
            }
        }

        if (findAndAttachMode2(child))
            return true;
    }

    return false;
}

