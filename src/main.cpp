// ============================================================
// UPDATE MODE 2 VALUES
// ============================================================

static void updateCANScreen()
{
    if (!canScreen)
        return;

    if (lv_scr_act() != canScreen)
        return;

    uint32_t now = millis();

    if (now - lastCANScreenUpdate < 200)
        return;

    lastCANScreenUpdate = now;

    bool rpmOK = fresh(
        trijekt.rpmValid,
        trijekt.lastRpmMs,
        RPM_TIMEOUT_MS
    );

    bool throttleOK = fresh(
        trijekt.throttleValid,
        trijekt.lastThrottleMs
    );

    bool tempOK = fresh(
        trijekt.tempValid,
        trijekt.lastTempMs
    );

    bool oilOK = fresh(
        trijekt.oilTempValid,
        trijekt.lastOilMs
    );

    bool pressureOK = fresh(
        trijekt.pressureValid,
        trijekt.lastPressureMs
    );

    bool lambda1OK = fresh(
        trijekt.lambda1Valid,
        trijekt.lastLambdaMs
    );

    bool lambda2OK = fresh(
        trijekt.lambda2Valid,
        trijekt.lastLambdaMs
    );

    bool batteryOK = fresh(
        trijekt.batteryValid,
        trijekt.lastBatteryMs
    );

    // ========================================================
    // UPDATE EVERY ENABLED LABEL
    // ========================================================

    for (int i = 0; i < CAN_VALUE_COUNT; i++) {

        if (!mode2Layout[i].enabled)
            continue;

        lv_obj_t *label = canValueLabels[i];

        if (!label)
            continue;

        bool valid = false;

        float floatValue = 0.0f;
        uint32_t intValue = 0;

        bool isFloat = false;
        int decimals = 1;

        const char *unit = "";

        switch (i)
        {
            // ------------------------------------------------
            // RPM
            // ------------------------------------------------

            case M2_RPM:
                valid = rpmOK;
                intValue = trijekt.rpm;
                break;

            // ------------------------------------------------
            // TORQUE
            // ------------------------------------------------

            case M2_TORQUE:
                valid = rpmOK;
                intValue = trijekt.torque;
                unit = " Nm";
                break;

            // ------------------------------------------------
            // MOTOR STATUS
            // ------------------------------------------------

            case M2_STATUS:
                valid = rpmOK;
                intValue = trijekt.motorStatus;
                break;

            // ------------------------------------------------
            // FUEL CONSUMPTION
            // ------------------------------------------------

            case M2_FUEL:
                valid = rpmOK;
                floatValue = trijekt.fuelConsumption;
                isFloat = true;
                unit = " L/h";
                break;

            // ------------------------------------------------
            // THROTTLE
            // ------------------------------------------------

            case M2_THROTTLE:
                valid = throttleOK;
                floatValue = trijekt.throttleDK;
                isFloat = true;
                unit = "%";
                break;

            // ------------------------------------------------
            // PEDAL
            // ------------------------------------------------

            case M2_PEDAL:
                valid = throttleOK;
                floatValue = trijekt.throttlePedal;
                isFloat = true;
                unit = "%";
                break;

            // ------------------------------------------------
            // E-GAS
            // ------------------------------------------------

            case M2_EGAS:
                valid = throttleOK;
                intValue = trijekt.egasControl;
                break;

            // ------------------------------------------------
            // E-GAS TARGET
            // ------------------------------------------------

            case M2_ETARGET:
                valid = throttleOK;
                floatValue = trijekt.egasTarget;
                isFloat = true;
                unit = " deg";
                break;

            // ------------------------------------------------
            // ENGINE TEMP
            // ------------------------------------------------

            case M2_ENGINE_TEMP:
                valid = tempOK;
                floatValue = trijekt.engineTemp;
                isFloat = true;
                unit = " C";
                break;

            // ------------------------------------------------
            // AIR TEMP
            // ------------------------------------------------

            case M2_AIR_TEMP:
                valid = tempOK;
                floatValue = trijekt.airTemp;
                isFloat = true;
                unit = " C";
                break;

            // ------------------------------------------------
            // ECU INTERNAL TEMP
            // ------------------------------------------------

            case M2_ECU_TEMP:
                valid = tempOK;
                floatValue = trijekt.internalTemp;
                isFloat = true;
                unit = " C";
                break;

            // ------------------------------------------------
            // OIL TEMP
            // ------------------------------------------------

            case M2_OIL_TEMP:
                valid = oilOK;
                floatValue = trijekt.oilTemp;
                isFloat = true;
                unit = " C";
                break;

            // ------------------------------------------------
            // INTAKE PRESSURE
            // ------------------------------------------------

            case M2_INTAKE:
                valid = pressureOK;
                intValue = trijekt.intakePressure;
                unit = " hPa";
                break;

            // ------------------------------------------------
            // EXTERNAL PRESSURE
            // ------------------------------------------------

            case M2_EXTERNAL:
                valid = pressureOK;
                intValue = trijekt.externalPressure;
                unit = " hPa";
                break;

            // ------------------------------------------------
            // FUEL PRESSURE
            // ------------------------------------------------

            case M2_FUEL_PRESSURE:
                valid = pressureOK;
                intValue = trijekt.fuelPressure;
                unit = " kPa";
                break;

            // ------------------------------------------------
            // OIL PRESSURE
            // ------------------------------------------------

            case M2_OIL_PRESSURE:
                valid = pressureOK;
                intValue = trijekt.oilPressure;
                unit = " kPa";
                break;

            // ------------------------------------------------
            // LAMBDA 1
            // ------------------------------------------------

            case M2_LAMBDA1:
                valid = lambda1OK;
                floatValue = trijekt.lambda1;
                isFloat = true;
                decimals = 3;
                break;

            // ------------------------------------------------
            // LAMBDA 2
            // ------------------------------------------------

            case M2_LAMBDA2:
                valid = lambda2OK;
                floatValue = trijekt.lambda2;
                isFloat = true;
                decimals = 3;
                break;

            // ------------------------------------------------
            // BATTERY
            // ------------------------------------------------

            case M2_BATTERY:
                valid = batteryOK;
                floatValue = trijekt.battery;
                isFloat = true;
                decimals = 2;
                unit = " V";
                break;

            // ------------------------------------------------
            // MAX RPM
            // ------------------------------------------------

            case M2_MAX_RPM:
                valid = rpm_max > 0;
                intValue = rpm_max;
                break;

            default:
                break;
        }

        // ====================================================
        // FORMAT VALUE
        // ====================================================

        char text[80];

        if (!valid) {

            snprintf(
                text,
                sizeof(text),
                "%s: ---",
                mode2Layout[i].name
            );
        }
        else if (isFloat) {

            snprintf(
                text,
                sizeof(text),
                "%s: %.*f%s",
                mode2Layout[i].name,
                decimals,
                (double)floatValue,
                unit
            );
        }
        else {

            snprintf(
                text,
                sizeof(text),
                "%s: %lu%s",
                mode2Layout[i].name,
                (unsigned long)intValue,
                unit
            );
        }

        // ====================================================
        // UPDATE LVGL LABEL
        // ====================================================

        lv_label_set_text(
            label,
            text
        );
    }
}

// ============================================================
// SETUP
// ============================================================

void setup()
{
    Serial.begin(115200);

    delay(300);

    Serial.println();
    Serial.println("====================================");
    Serial.println("WAVESHARE TRIJEKT PREMIUM 3.0");
    Serial.println("RWB DASHBOARD");
    Serial.println("MODE 1 / MODE 2");
    Serial.println("HOLLOW22 FONT");
    Serial.println("REAL CAN - NO SIMULATION");
    Serial.println("====================================");

    // ========================================================
    // INITIALIZE ECU DATA
    // ========================================================

    ecu = ECUData{};
    trijekt = TrijektValues{};

    // ========================================================
    // INITIALIZE WAVESHARE DISPLAY
    // ========================================================

    board = new Board();

    board->init();

#if LVGL_PORT_AVOID_TEARING_MODE

    {
        auto lcd = board->getLCD();

        lcd->configFrameBufferNumber(
            LVGL_PORT_DISP_BUFFER_NUM
        );
    }

#endif

    assert(board->begin());

    // ========================================================
    // INITIALIZE LVGL
    // ========================================================

    lvgl_port_init(
        board->getLCD(),
        board->getTouch()
    );

    lvgl_port_lock(-1);

    // Original RWB dashboard
    ui_init();

    // Save MODE 1 screen
    if (objects.label_batt) {

        originalScreen =
            lv_obj_get_screen(objects.label_batt);
    }
    else {

        originalScreen = lv_scr_act();
    }

    // Create MODE 2 screen with Hollow22 font
    createCANScreen();

    // Connect MODE 2 touch button
    bool mode2Found =
        findAndAttachMode2(originalScreen);

    if (!mode2Found) {

        Serial.println(
            "WARNING: MODE 2 BUTTON NOT FOUND"
        );

        Serial.println(
            "Connect open_trijekt_mode2() in screens.c"
        );
    }

    // Start on MODE 1
    if (originalScreen) {
        lv_scr_load(originalScreen);
    }

    lvgl_port_unlock();

    Serial.println("LVGL UI READY");

    // ========================================================
    // INITIALIZE CAN
    // ========================================================

    can_ok = waveshare_twai_init();

    if (can_ok) {

        Serial.println("CAN INITIALIZED");
    }
    else {

        Serial.println("CAN INITIALIZATION FAILED");
    }

    // ========================================================
    // INITIALIZE ESP-NOW
    // ========================================================

    if (espnow_init_simple()) {

        Serial.println("ESP-NOW INITIALIZED");
    }
    else {

        Serial.println("ESP-NOW FAILED");
    }

    Serial.println();
    Serial.println("WAITING FOR TRIJEKT CAN DATA");
    Serial.println();
}

// ============================================================
// MAIN LOOP
// ============================================================

void loop()
{
    uint32_t now = millis();

    // ========================================================
    // 1. READ CAN FRAMES
    // ========================================================

    if (can_ok) {

        twai_message_t msg;

        for (int i = 0; i < CAN_BATCH_SIZE; i++) {

            esp_err_t result = twai_receive(
                &msg,
                0
            );

            if (result != ESP_OK)
                break;

            recordCANFrame(msg);

            decodeCANMessage(msg);
        }
    }

    // ========================================================
    // 2. ECU HOUSEKEEPING
    // ========================================================

    updateECUHousekeeping();

    // ========================================================
    // 3. UPDATE LVGL
    // ========================================================

    static uint32_t lastUI = 0;

    now = millis();

    if (now - lastUI >= UI_INTERVAL_MS) {

        lvgl_port_lock(-1);

        // ====================================================
        // MODE 1 - ORIGINAL RWB DASHBOARD
        // ====================================================

        if (lv_scr_act() == originalScreen) {

            update_mock_rpm();
            update_mock_throttle();
            update_mock_lambda();
            update_mock_motor_temp();
        }

        // ====================================================
        // MODE 2 - HOLLOW22 CAN VALUES
        // ====================================================

        if (lv_scr_act() == canScreen) {

            updateCANScreen();
        }

        lvgl_port_unlock();

        lastUI = millis();
    }

    // ========================================================
    // 4. ESP-NOW
    // ========================================================

    sendEspNowValues();

    // ========================================================
    // 5. SERIAL LIVE VALUES
    // ========================================================

    static uint32_t lastDebug = 0;

    now = millis();

    if (now - lastDebug >= DEBUG_INTERVAL_MS) {

        printAllValues();

        lastDebug = millis();
    }

    // ========================================================
    // 6. CAN DIAGNOSTICS
    // ========================================================

    now = millis();

    if (
        now - canLastReportMs >=
        CAN_DEBUG_INTERVAL_MS
    ) {

        printCANDiagnostics();
    }

    // ========================================================
    // 7. SHORT DELAY
    // ========================================================

    delay(1);
}
