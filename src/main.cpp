static inline uint16_t U16LE(const uint8_t *d)
{
    return uint16_t(d[0]) |
           (uint16_t(d[1]) << 8);
}

static inline int16_t S16LE(const uint8_t *d)
{
    return (int16_t)U16LE(d);
}

static bool validRPM(uint16_t value)
{
    return value <= MAX_RPM;
}

static bool validTemp(float value)
{
    return value >= -40.0f &&
           value <= 180.0f;
}

static bool validBattery(float value)
{
    return value >= 8.0f &&
           value <= 18.0f;
}

static bool validLambda(float value)
{
    return isfinite(value) &&
           value >= 0.50f &&
           value <= 10.00f;
}

static bool fresh(
    bool valid,
    uint32_t lastMs,
    uint32_t timeoutMs = SENSOR_TIMEOUT_MS
)
{
    return valid &&
           (millis() - lastMs <= timeoutMs);
}

// ============================================================
// TRIJEKT CAN DECODER
// ============================================================

void decodeCANMessage(const twai_message_t &m)
{
    if (m.extd || m.rtr)
        return;

    if (m.data_length_code != 8)
        return;

    uint32_t now = millis();

    const uint8_t *d = m.data;

    bool decoded = false;

    switch (m.identifier)
    {
        // CAN 700 - RPM / TORQUE / STATUS / FUEL

        case CAN_A + 0:
        {
            uint16_t rpm = U16LE(d);

            if (!validRPM(rpm))
                break;

            trijekt.rpm = rpm;
            trijekt.torque = U16LE(d + 2);
            trijekt.motorStatus = U16LE(d + 4);

            trijekt.fuelConsumption =
                U16LE(d + 6) * 0.1f;

            trijekt.rpmValid = true;
            trijekt.lastRpmMs = now;

            ecu.rpm = rpm;
            lastRpmUpdateMs = now;

            if (rpm > rpm_max)
                rpm_max = rpm;

            decoded = true;
            break;
        }

        // CAN 701 - THROTTLE / PEDAL / E-GAS

        case CAN_A + 1:
        {
            trijekt.throttleDK =
                U16LE(d) * 0.1f;

            trijekt.throttlePedal =
                U16LE(d + 2) * 0.1f;

            trijekt.egasControl =
                U16LE(d + 4);

            trijekt.egasTarget =
                U16LE(d + 6) * 0.1f;

            trijekt.throttleValid = true;
            trijekt.lastThrottleMs = now;

            ecu.throttle_dk = trijekt.throttleDK;
            ecu.throttle_pedal = trijekt.throttlePedal;

            decoded = true;
            break;
        }

        // CAN 702 - ENGINE / AIR / ECU TEMP

        case CAN_A + 2:
        {
            float engineTemp =
                S16LE(d) * 0.1f;

            float airTemp =
                S16LE(d + 2) * 0.1f;

            float internalTemp =
                S16LE(d + 6) * 0.1f;

            if (!validTemp(engineTemp))
                break;

            trijekt.engineTemp = engineTemp;
            trijekt.airTemp = airTemp;
            trijekt.internalTemp = internalTemp;

            trijekt.tempValid = true;
            trijekt.lastTempMs = now;

            ecu.motor = engineTemp;

            decoded = true;
            break;
        }

        // CAN 703 - OIL TEMPERATURE

        case CAN_A + 3:
        {
            float oilTemp =
                S16LE(d) * 0.1f;

            if (!validTemp(oilTemp))
                break;

            trijekt.oilTemp = oilTemp;

            trijekt.oilTempValid = true;
            trijekt.lastOilMs = now;

            decoded = true;
            break;
        }

        // CAN 704 - PRESSURES

        case CAN_A + 4:
        {
            trijekt.intakePressure =
                U16LE(d);

            trijekt.externalPressure =
                U16LE(d + 2);

            trijekt.fuelPressure =
                U16LE(d + 4);

            trijekt.oilPressure =
                U16LE(d + 6);

            trijekt.pressureValid = true;
            trijekt.lastPressureMs = now;

            decoded = true;
            break;
        }

        // CAN 705 - LAMBDA

        case CAN_A + 5:
        {
            float lambda1 =
                U16LE(d) * 0.001f;

            float lambda2 =
                U16LE(d + 2) * 0.001f;

            // Diagnose: CAN ID 705 (decimal) raw Lambda payload.
            static uint32_t lastLambdaDebugMs = 0;
            if (PRINT_LAMBDA_RAW && now - lastLambdaDebugMs >= 1000) {
                Serial.printf(
                    "LAMBDA CAN ID=%lu RAW=%02X %02X %02X %02X %02X %02X %02X %02X | L1=%.3f L2=%.3f\n",
                    (unsigned long)m.identifier,
                    d[0], d[1], d[2], d[3], d[4], d[5], d[6], d[7],
                    (double)lambda1, (double)lambda2
                );
                lastLambdaDebugMs = now;
            }

            trijekt.lambda1 = lambda1;
            trijekt.lambda2 = lambda2;

            trijekt.lambda1Valid =
                validLambda(lambda1);

            trijekt.lambda2Valid =
                validLambda(lambda2);

            trijekt.lastLambdaMs = now;

            if (trijekt.lambda1Valid)
                ecu.lambda = lambda1;

            decoded = true;
            break;
        }

        // CAN 711 - BATTERY

        case CAN_B + 1:
        {
            float battery =
                U16LE(d + 2) * 0.001f;

            if (!validBattery(battery))
                break;

            trijekt.battery = battery;

            trijekt.batteryValid = true;
            trijekt.lastBatteryMs = now;

            ecu.batt = battery;

            decoded = true;
            break;
        }

        default:
            break;
    }

    if (decoded) {
        lastCanUpdateMs = now;
        ecu.last_update = now;
    }
}

// ============================================================
// ECU HOUSEKEEPING
// ============================================================

void updateECUHousekeeping()
{
    bool rpmFresh = fresh(
        trijekt.rpmValid,
        trijekt.lastRpmMs,
        RPM_TIMEOUT_MS
    );

    bool lambdaFresh = fresh(
        trijekt.lambda1Valid,
        trijekt.lastLambdaMs
    );

    ecu.data_valid = rpmFresh ? 1 : 0;
    ecu.lambda_valid = lambdaFresh ? 1 : 0;

    ecu.engine_running =
        rpmFresh && ecu.rpm > 100;

    if (!rpmFresh)
        ecu.rpm = 0;
}

