static void printFloatValue(
    const char *label,
    float value,
    const char *unit,
    bool valid,
    uint32_t lastMs,
    uint8_t decimals = 1,
    uint32_t timeoutMs = SENSOR_TIMEOUT_MS
)
{
    Serial.printf("%-19s : ", label);

    if (fresh(valid, lastMs, timeoutMs)) {

        Serial.print(value, decimals);

        if (unit && unit[0]) {
            Serial.print(" ");
            Serial.print(unit);
        }

        Serial.println();
    }
    else {
        Serial.println("--");
    }
}

