// ============================================================
// MAIN LOOP
// ============================================================

void loop()
{
    uint32_t now = millis();

    // ========================================================
    // 1. READ CAN FRAMES
    // ========================================================

    if (can_ok) {

        twai_message_t msg;
        const uint32_t canStartUs = micros();

        for (int i = 0; i < CAN_BATCH_SIZE; i++) {
            if ((uint32_t)(micros() - canStartUs) >= CAN_TIME_BUDGET_US)
                break;

            esp_err_t result = twai_receive(
                &msg,
                0
            );

            if (result != ESP_OK)
                break;

            recordCANFrame(msg);

            decodeCANMessage(msg);
        }
    }

    // ========================================================
    // 2. ECU HOUSEKEEPING
    // ========================================================

    updateECUHousekeeping();

    // Demo overrides displayed values after real-CAN housekeeping.
    updateDashboardDemo();

    // ========================================================
    // 3. UPDATE LVGL
    // ========================================================

    static uint32_t lastUI = 0;

    now = millis();

    if (now - lastUI >= UI_INTERVAL_MS) {

        lvgl_port_lock(-1);

        // ====================================================
        // MODE 1 - ORIGINAL RWB DASHBOARD
        // ====================================================

        if (lv_scr_act() == originalScreen) {

            update_mock_rpm();
            update_mock_throttle();
            update_mock_lambda();
            update_mock_motor_temp();
        }

        // ====================================================
        // MODE 3 - ALL ECU CAN VALUES
        // ====================================================

        if (lv_scr_act() == canScreen) {

            updateCANScreen();
        }

        lvgl_port_unlock();

        lastUI = millis();
    }

    // ========================================================
    // 4. ESP-NOW
    // ========================================================

    // Do not transmit simulated ECU data to the M5Stack/Nixie.
    if (!DASH_DEMO_MODE) sendEspNowValues();

    // ========================================================
    // 5. SERIAL LIVE VALUES
    // ========================================================

    static uint32_t lastDebug = 0;

    now = millis();

    if (PRINT_LIVE_VALUES && now - lastDebug >= DEBUG_INTERVAL_MS) {

        printAllValues();

        lastDebug = millis();
    }

    // ========================================================
    // 6. CAN DIAGNOSTICS
    // ========================================================

    now = millis();

    if (
        PRINT_CAN_DIAGNOSTICS &&
        now - canLastReportMs >=
        CAN_DEBUG_INTERVAL_MS
    ) {

        printCANDiagnostics();
    }

    // ========================================================
    // Nixie UART and animations (no LVGL theme changes).
    airTick();
    airWifiTick();

    // 7. SHORT DELAY
    // ========================================================

    delay(1);
}
