struct CANIDStats {

    uint32_t count = 0;
    uint32_t lastMs = 0;

    uint8_t lastData[8] = {0};
    uint8_t dlc = 0;
};

static CANIDStats canStats[2048];

static uint32_t totalCANFrames = 0;
static uint32_t lastCANCount = 0;

static uint32_t extendedFrames = 0;
static uint32_t remoteFrames = 0;

static uint32_t canLastReportMs = 0;

// ============================================================
// RECORD CAN FRAME
// ============================================================

static void recordCANFrame(const twai_message_t &m)
{
    totalCANFrames++;

    if (m.extd) {
        extendedFrames++;
        return;
    }

    if (m.rtr) {
        remoteFrames++;
        return;
    }

    if (m.identifier >= 2048)
        return;

    CANIDStats &s = canStats[m.identifier];

    s.count++;
    s.lastMs = millis();
    s.dlc = m.data_length_code;

    memset(s.lastData, 0, sizeof(s.lastData));

    uint8_t len = m.data_length_code;

    if (len > 8)
        len = 8;

    memcpy(s.lastData, m.data, len);
}

// ============================================================
// PRINT CAN DIAGNOSTICS
// ============================================================

static void printCANDiagnostics()
{
    uint32_t now = millis();
    uint32_t elapsed = now - canLastReportMs;

    uint32_t newFrames =
        totalCANFrames - lastCANCount;

    float rate = 0.0f;

    if (elapsed > 0) {
        rate = newFrames * 1000.0f / elapsed;
    }

    Serial.println();
    Serial.println("====================================");
    Serial.println("CAN DIAGNOSTICS");
    Serial.println("====================================");

    Serial.printf(
        "Total frames: %lu\n",
        (unsigned long)totalCANFrames
    );

    Serial.printf(
        "Frame rate: %.1f/s\n",
        rate
    );

    Serial.printf(
        "Extended: %lu\n",
        (unsigned long)extendedFrames
    );

    Serial.printf(
        "Remote: %lu\n",
        (unsigned long)remoteFrames
    );

    Serial.println("ID  COUNT  AGE(ms)  DATA");

    for (int id = 0; id < 2048; id++) {

        const CANIDStats &s = canStats[id];

        if (s.count == 0)
            continue;

        Serial.printf(
            "%d  %lu  %lu  ",
            id,
            (unsigned long)s.count,
            (unsigned long)(now - s.lastMs)
        );

        for (int i = 0; i < s.dlc && i < 8; i++) {
            Serial.printf("%02X ", s.lastData[i]);
        }

        Serial.println();
    }

    twai_status_info_t status{};

    if (twai_get_status_info(&status) == ESP_OK) {

        Serial.printf(
            "RX queue: %lu\n",
            (unsigned long)status.msgs_to_rx
        );

        Serial.printf(
            "RX missed: %lu\n",
            (unsigned long)status.rx_missed_count
        );

        Serial.printf(
            "RX overrun: %lu\n",
            (unsigned long)status.rx_overrun_count
        );

        Serial.printf(
            "Bus errors: %lu\n",
            (unsigned long)status.bus_error_count
        );

        Serial.printf(
            "TX failed: %lu\n",
            (unsigned long)status.tx_failed_count
        );
    }

    Serial.println("====================================");

    lastCANCount = totalCANFrames;
    canLastReportMs = millis();
}

